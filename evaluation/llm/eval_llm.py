import argparse
import importlib
import json
from collections import defaultdict
from pathlib import Path
import sys

from metrics import (
    build_confusion_matrix,
    compare_slots,
    field_accuracy,
    merge_slot_stats,
    normalize_api_call,
    normalize_intent,
    normalize_output,
    precision_recall_f1,
)

OPTIONAL_SLOTS = {"day", "date", "reference"}


def load_cases(path: Path) -> list[dict]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, list):
        raise ValueError("Cases file must contain a list of cases")
    return data


def load_function(module_path: str, function_name: str):
    module = importlib.import_module(module_path)
    func = getattr(module, function_name, None)
    if func is None:
        raise AttributeError(f"Function '{function_name}' not found in {module_path}")
    return func


def adapt_history(history: list[dict]) -> list[dict]:
    adapted = []
    for item in history or []:
        role = item.get("role", "user")
        text = item.get("text", "")
        adapted.append({"role": role, "text": text, "content": text})
    return adapted


def classify_failure(intent_ok: bool, api_ok: bool, slots_ok: bool) -> str:
    if not intent_ok:
        return "intent"
    if not api_ok:
        return "api_call"
    if not slots_ok:
        return "slot"
    return "other"


def write_failures(path: Path, failures: dict[str, list[dict]]) -> None:
    lines = ["# Evaluation Failures", "", "Generated by eval_llm.py", ""]
    for failure_type in sorted(failures.keys()):
        lines.append(f"## {failure_type}")
        for item in failures[failure_type]:
            lines.append(f"- Case {item['case_id']} ({item['category']})")
            if item.get("history"):
                lines.append("  - History:")
                for turn in item["history"]:
                    role = turn.get("role", "user")
                    text = turn.get("text", "")
                    lines.append(f"    - {role}: {text}")
            lines.append(f"  - User: {item['user_utterance']}")
            lines.append(f"  - Expected intent: {item['expected_intent']}")
            lines.append(f"  - Predicted intent: {item['predicted_intent']}")
            lines.append(f"  - Expected slots: {item['expected_slots']}")
            lines.append(f"  - Predicted slots: {item['predicted_slots']}")
            lines.append(f"  - Expected api_call: {item['expected_api_call']}")
            lines.append(f"  - Predicted api_call: {item['predicted_api_call']}")
            if item.get("assistant_reply"):
                lines.append(f"  - Assistant reply: {item['assistant_reply']}")
            if item.get("error"):
                lines.append(f"  - Error: {item['error']}")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_report(path: Path, summary: dict, case_counts: dict[str, int]) -> None:
    lines = [
        "# LLM Evaluation Report",
        "",
        "This report summarizes intrinsic and extrinsic evaluation results for the LLM/NLU layer.",
        "Generated by eval_llm.py.",
        "",
        "## Evaluation Scope",
        "",
        "We evaluate intent classification, slot filling, structured API call prediction,",
        "end-to-end task success, context/coreference handling, and robustness to paraphrases",
        "and minor ASR-like noise.",
        "",
        "## Dataset Composition",
        "",
    ]

    for category in sorted(case_counts.keys()):
        lines.append(f"- {category}: {case_counts[category]} cases")

    lines.extend([
        "",
        "## Metrics",
        "",
        f"- Intent accuracy: {summary['intent_accuracy']:.3f}",
        f"- API method+endpoint accuracy: {summary['api_call_accuracy']:.3f}",
        f"- Task success rate: {summary['task_success_rate']:.3f}",
        f"- Coreference success rate: {summary['coref_success_rate']:.3f}",
        f"- Robustness success rate: {summary['robust_success_rate']:.3f}",
        f"- Robustness delta vs clean: {summary['robust_delta']:.3f}",
        "",
        "### Slot Filling (Micro)",
        f"- Precision: {summary['slot_micro_precision']:.3f}",
        f"- Recall: {summary['slot_micro_recall']:.3f}",
        f"- F1: {summary['slot_micro_f1']:.3f}",
        "",
        "### Slot Filling (Macro)",
        f"- Precision: {summary['slot_macro_precision']:.3f}",
        f"- Recall: {summary['slot_macro_recall']:.3f}",
        f"- F1: {summary['slot_macro_f1']:.3f}",
        "",
        "## Qualitative Error Analysis",
        "",
        "See failures.md for grouped failure cases and diffs.",
    ])

    path.write_text("\n".join(lines), encoding="utf-8")


def print_progress(index: int, total: int, case_id: str, category: str) -> None:
    message = f"[{index}/{total}] {case_id} ({category})"
    sys.stdout.write("\r" + message + " " * max(0, 20 - len(message)))
    sys.stdout.flush()


def print_summary(summary: dict, category_success: dict[str, tuple[int, int]]) -> None:
    print("\n\n=== Evaluation Summary ===")
    rows = [
        ("Intent Accuracy", summary.get("intent_accuracy", 0.0)),
        ("API Accuracy", summary.get("api_call_accuracy", 0.0)),
        ("Task Success", summary.get("task_success_rate", 0.0)),
        ("Coref Success", summary.get("coref_success_rate", 0.0)),
        ("Robust Success", summary.get("robust_success_rate", 0.0)),
        ("Robust Delta", summary.get("robust_delta", 0.0)),
        ("Slot F1 (micro)", summary.get("slot_micro_f1", 0.0)),
        ("Slot F1 (macro)", summary.get("slot_macro_f1", 0.0)),
    ]
    label_width = max(len(label) for label, _ in rows)
    for label, value in rows:
        print(f"{label:<{label_width}} : {value:.3f}")

    if category_success:
        print("\n=== Task Success by Category ===")
        cat_label_width = max(len(name) for name in category_success.keys())
        for category in sorted(category_success.keys()):
            success, total = category_success[category]
            rate = success / total if total else 0.0
            print(f"{category:<{cat_label_width}} : {success}/{total} ({rate:.3f})")


def main() -> None:
    parser = argparse.ArgumentParser(description="Run LLM/NLU evaluation.")
    parser.add_argument("--cases", required=True, help="Path to eval_cases.json")
    parser.add_argument("--module", required=True, help="Module path to import")
    parser.add_argument(
        "--function",
        required=True,
        choices=["nlu_parse", "assistant_step"],
        help="Function name to call",
    )
    parser.add_argument("--out", required=True, help="Path to results.json")
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress per-case progress output",
    )
    args = parser.parse_args()

    cases_path = Path(args.cases)
    results_path = Path(args.out)
    failures_path = results_path.parent / "failures.md"
    report_path = results_path.parent / "report_eval.md"

    cases = load_cases(cases_path)
    func = load_function(args.module, args.function)

    confusion = defaultdict(lambda: defaultdict(int))
    slot_stats_list = []

    total_cases = 0
    intent_correct_count = 0
    api_correct_count = 0
    task_success_count = 0
    coref_success_count = 0
    coref_total = 0
    robust_success_count = 0
    robust_total = 0
    clean_success_count = 0
    clean_total = 0

    params_correct = 0
    params_total = 0
    body_correct = 0
    body_total = 0

    case_results = []
    failures = defaultdict(list)
    category_counts = defaultdict(int)

    for index, case in enumerate(cases, start=1):
        if not args.quiet:
            print_progress(index, len(cases), case.get("case_id", "unknown"), case.get("category", "unknown"))
        total_cases += 1
        category = case.get("category", "unknown")
        category_counts[category] += 1

        expected = case.get("expected", {})
        expected_intent = normalize_intent(expected.get("intent", ""))
        expected_slots = expected.get("slots") or {}
        expected_api = normalize_api_call(expected.get("api_call"))

        history = adapt_history(case.get("history", []))
        user_utterance = case.get("user_utterance", "")

        try:
            raw_pred = func(history, user_utterance)
        except Exception as exc:
            raw_pred = {"intent": "", "slots": {}, "api_call": {}, "assistant_reply": ""}
            raw_pred["_error"] = str(exc)

        pred = normalize_output(raw_pred)
        pred_intent = normalize_intent(pred.get("intent", ""))
        pred_slots = pred.get("slots") or {}
        pred_api = normalize_api_call(pred.get("api_call"))

        intent_ok = expected_intent == pred_intent
        confusion[expected_intent][pred_intent] += 1
        if intent_ok:
            intent_correct_count += 1

        optional_slots = set(expected.get("optional_slots", [])) | OPTIONAL_SLOTS
        slots_result, slot_stats = compare_slots(expected_slots, pred_slots, optional_slots)
        slot_stats_list.append(slot_stats)
        slots_ok = all(slots_result.values()) if expected_slots else True

        api_ok = (
            expected_api.get("method") == pred_api.get("method")
            and expected_api.get("endpoint") == pred_api.get("endpoint")
        )
        if api_ok:
            api_correct_count += 1

        params_c, params_t = field_accuracy(expected_api.get("params", {}), pred_api.get("params", {}))
        body_c, body_t = field_accuracy(expected_api.get("body", {}), pred_api.get("body", {}))
        params_correct += params_c
        params_total += params_t
        body_correct += body_c
        body_total += body_t

        task_success = intent_ok and api_ok and slots_ok
        if task_success:
            task_success_count += 1

        is_coref = "coref" in category
        if is_coref:
            coref_total += 1
            if task_success:
                coref_success_count += 1

        is_robust = "robust" in category
        if is_robust:
            robust_total += 1
            if task_success:
                robust_success_count += 1
        else:
            clean_total += 1
            if task_success:
                clean_success_count += 1

        if not task_success:
            failure_type = classify_failure(intent_ok, api_ok, slots_ok)
            failures[failure_type].append({
                "case_id": case.get("case_id"),
                "category": category,
                "history": case.get("history", []),
                "user_utterance": user_utterance,
                "expected_intent": expected_intent,
                "predicted_intent": pred_intent,
                "expected_slots": expected_slots,
                "predicted_slots": pred_slots,
                "expected_api_call": expected_api,
                "predicted_api_call": pred_api,
                "assistant_reply": pred.get("assistant_reply", ""),
                "error": raw_pred.get("_error"),
            })

        case_results.append({
            "case_id": case.get("case_id"),
            "category": category,
            "expected": expected,
            "predicted": pred,
            "intent_correct": intent_ok,
            "slots_correct": slots_ok,
            "api_call_correct": api_ok,
            "task_success": task_success,
            "error": raw_pred.get("_error"),
        })

    if not args.quiet:
        sys.stdout.write("\r" + " " * 80 + "\r")

    slot_stats = merge_slot_stats(slot_stats_list)
    slot_metrics = {}
    micro_tp = micro_fp = micro_fn = 0

    for slot, stats in slot_stats.items():
        tp = stats["tp"]
        fp = stats["fp"]
        fn = stats["fn"]
        micro_tp += tp
        micro_fp += fp
        micro_fn += fn
        precision, recall, f1 = precision_recall_f1(tp, fp, fn)
        slot_metrics[slot] = {
            "precision": precision,
            "recall": recall,
            "f1": f1,
            "tp": tp,
            "fp": fp,
            "fn": fn,
        }

    micro_precision, micro_recall, micro_f1 = precision_recall_f1(micro_tp, micro_fp, micro_fn)

    macro_precision = 0.0
    macro_recall = 0.0
    macro_f1 = 0.0
    if slot_metrics:
        macro_precision = sum(m["precision"] for m in slot_metrics.values()) / len(slot_metrics)
        macro_recall = sum(m["recall"] for m in slot_metrics.values()) / len(slot_metrics)
        macro_f1 = sum(m["f1"] for m in slot_metrics.values()) / len(slot_metrics)

    summary = {
        "total_cases": total_cases,
        "intent_accuracy": intent_correct_count / total_cases if total_cases else 0.0,
        "api_call_accuracy": api_correct_count / total_cases if total_cases else 0.0,
        "task_success_rate": task_success_count / total_cases if total_cases else 0.0,
        "coref_success_rate": coref_success_count / coref_total if coref_total else 0.0,
        "robust_success_rate": robust_success_count / robust_total if robust_total else 0.0,
        "robust_delta": (robust_success_count / robust_total - clean_success_count / clean_total)
        if robust_total and clean_total
        else 0.0,
        "slot_micro_precision": micro_precision,
        "slot_micro_recall": micro_recall,
        "slot_micro_f1": micro_f1,
        "slot_macro_precision": macro_precision,
        "slot_macro_recall": macro_recall,
        "slot_macro_f1": macro_f1,
        "params_field_accuracy": params_correct / params_total if params_total else 0.0,
        "body_field_accuracy": body_correct / body_total if body_total else 0.0,
        "slot_metrics": slot_metrics,
        "confusion_matrix": build_confusion_matrix(confusion),
    }

    results = {
        "summary": summary,
        "cases": case_results,
    }

    results_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    write_failures(failures_path, failures)
    write_report(report_path, summary, category_counts)

    category_success = defaultdict(lambda: [0, 0])
    for case in case_results:
        category = case.get("category", "unknown")
        category_success[category][1] += 1
        if case.get("task_success"):
            category_success[category][0] += 1

    print("Evaluation complete")
    print(f"Results: {results_path}")
    print(f"Failures: {failures_path}")
    print(f"Report: {report_path}")
    print_summary(summary, {k: tuple(v) for k, v in category_success.items()})


if __name__ == "__main__":
    main()
